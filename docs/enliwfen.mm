      <li>
        The new element has an id corresponding to an<br/>element of the active document: The corresponding<br/>element of the active document will be replaced by<br/>the new element.
      </li>
      <li>
        The new element has an id without a<br/>corresponding element of the active document:

        <ul>
          <li>
            The&#xa0;launching element has defined a target<br/>element, which is part of the active document:<br/>The target element will be replaced by the<br/>new element.
          </li>
          <li>
            The launching element has defined more than<br/>one target element: The first target element<br/>will be replaced by the new element.
          </li>
          <li>
            The launching element has not defined a<br/>target element: The launching element will<br/>be replaced by the new element.
          </li>
        </ul>
      </li>
      <li>
        The new element has no id set:

        <ul>
          <li>
            The launching element has defined a target<br/>element, which is part of the active document:<br/>The target element will be replaced by the<br/>new element.
          </li>
          <li>
            The launching element has defined more than<br/>one target element: The target elements will<br/>be replaced by the new element.
          </li>
